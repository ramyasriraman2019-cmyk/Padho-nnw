def _extras():
    path = os.path.join(os.path.dirname(os.path.dirname(__file__)), "data", "passages_extra.json")
    if not os.path.exists(path):
        return {}
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


def passages_for(lang_code: str, level: int) -> list:
    """All passages for a language and level (built-in first, then extras)."""
    book = PASSAGES.get(lang_code, PASSAGES["en"])
    level = max(1, min(level, max(book)))
    out = [book[level]]
    out += _extras().get(lang_code, {}).get(str(level), [])
    return out
